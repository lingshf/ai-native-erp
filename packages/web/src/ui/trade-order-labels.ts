export type TradeOrderKey = keyof typeof tradeOrderEn;
export const tradeOrderResources = { zh: tradeOrderZh, en: tradeOrderEn } as const;

export function orderLabel(
  language: Language,
  key: TradeOrderKey,
  params: Readonly<Record<string, string | number>> = {},
): string {
  return tradeOrderResources[language][key].replace(/\{([^{}]+)\}/g, (_match, name: string) =>
    String(params[name] ?? `{${name}}`),
  );
}
